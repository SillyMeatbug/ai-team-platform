async def seed_agents() -> int:
    """Создать или обновить предустановленных агентов. Возвращает число затронутых записей."""
    factory = get_session_factory()
    touched = 0
    async with factory() as session:
        for cfg in PRESET_AGENTS:
            name = str(cfg["name"])
            # Идемпотентный upsert по name или role: не дублируем записи при повторном сидировании.
            stmt = select(Agent).where(
                or_(Agent.name == name, Agent.role == str(cfg["role"]))
            )
            agent = (await session.execute(stmt)).scalar_one_or_none()
            if agent is None:
                session.add(
                    Agent(
                        id=str(cfg["id"]),
                        name=name,
                        model=str(cfg["model"]),
                        role=str(cfg["role"]),
                        system_prompt=str(cfg["system_prompt"]),
                        color=str(cfg["color"]),
                        is_active=bool(cfg["is_active"]),
                    )
                )
                touched += 1
                continue

            sid = str(cfg["system_prompt"])
            smodel = str(cfg["model"])
            srole = str(cfg["role"])
            scolor = str(cfg["color"])
            sactive = bool(cfg["is_active"])
            if (
                agent.system_prompt != sid
                or agent.model != smodel
                or agent.role != srole
                or agent.color != scolor
                or agent.is_active != sactive
            ):
                agent.system_prompt = sid
                agent.model = smodel
                agent.role = srole
                agent.color = scolor
                agent.is_active = sactive
                touched += 1

        if touched:
            await session.commit()
    log_payload(logger, logging.INFO, "agents_seed_complete", touched=touched)
    return touched
